import {
  cpSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

import Beasties from "beasties";

import {
  collectPayloadReport,
  type PayloadGroup,
  type PayloadReport,
} from "./report-payload";

interface CriticalCssExperimentOptions {
  outputDir: string;
  reportFile: string;
  sourceDir: string;
}

const defaultOutputRoot = path.join("tmp", "critical-css-experiment");

/**
 * Runs a bounded Beasties critical-CSS experiment on a copied build output.
 *
 * This command never mutates `dist/`; it produces a copied output and a report
 * so the tradeoff can be evaluated before any production adoption decision.
 *
 * @param options Experiment paths.
 * @param options.sourceDir Built output directory to copy and measure.
 * @param options.outputDir Temporary directory for the processed output copy.
 * @param options.reportFile Markdown report path.
 * @returns Markdown experiment report.
 */
export async function runCriticalCssExperiment({
  outputDir,
  reportFile,
  sourceDir,
}: CriticalCssExperimentOptions): Promise<string> {
  const baseline = collectPayloadReport({ distDir: sourceDir });

  rmSync(outputDir, { force: true, recursive: true });
  mkdirSync(path.dirname(outputDir), { recursive: true });
  cpSync(sourceDir, outputDir, { recursive: true });

  const beasties = new Beasties({
    fonts: false,
    logLevel: "silent",
    noscriptFallback: true,
    path: outputDir,
    preload: "swap",
    pruneSource: false,
    publicPath: "/",
    reduceInlineStyles: false,
  });

  const htmlFiles = listFiles(outputDir).filter(
    (filePath) => path.extname(filePath).toLowerCase() === ".html",
  );

  for (const htmlFile of htmlFiles) {
    const html = readFileSync(htmlFile, "utf8");
    const processed = await beasties.process(html);
    writeFileSync(htmlFile, processed);
  }

  const experiment = collectPayloadReport({ distDir: outputDir });
  const report = formatCriticalCssExperimentReport({
    baseline,
    experiment,
    htmlFilesProcessed: htmlFiles.length,
    outputDir,
    sourceDir,
  });

  mkdirSync(path.dirname(reportFile), { recursive: true });
  writeFileSync(reportFile, `${report}\n`);

  return report;
}

interface CriticalCssExperimentReportInput {
  baseline: PayloadReport;
  experiment: PayloadReport;
  htmlFilesProcessed: number;
  outputDir: string;
  sourceDir: string;
}

function formatCriticalCssExperimentReport({
  baseline,
  experiment,
  htmlFilesProcessed,
  outputDir,
  sourceDir,
}: CriticalCssExperimentReportInput): string {
  const lines = [
    "# Critical CSS Experiment",
    "",
    "This report is generated by `bun run payload:critical-css:experiment`.",
    "The experiment copies built output, runs Beasties on the copy, and measures",
    "raw/gzip/Brotli payload deltas. It does not mutate production `dist/`.",
    "",
    "## Scenario",
    "",
    `- Source: \`${sourceDir}\``,
    `- Output copy: \`${outputDir}\``,
    `- HTML files processed: ${htmlFilesProcessed}`,
    '- Beasties options: `preload: "swap"`, `noscriptFallback: true`,',
    "  `pruneSource: false`, `reduceInlineStyles: false`, `fonts: false`.",
    "",
    "## Payload Deltas",
    "",
    payloadDeltaTable([
      ["All assets", baseline.allFiles, experiment.allFiles],
      [
        "Gzip/Brotli-eligible assets",
        baseline.gzipEligibleFiles,
        experiment.gzipEligibleFiles,
      ],
      ["HTML assets", baseline.htmlFiles, experiment.htmlFiles],
      [
        "CSS assets",
        groupByExtension(baseline, ".css"),
        groupByExtension(experiment, ".css"),
      ],
      [
        "JS assets",
        groupByExtension(baseline, ".js"),
        groupByExtension(experiment, ".js"),
      ],
    ]),
    "",
    "## Initial Recommendation",
    "",
    recommendationText(baseline, experiment),
  ];

  return lines.join("\n");
}

function groupByExtension(
  report: PayloadReport,
  extension: string,
): PayloadGroup {
  return (
    report.byExtension.find((group) => group.extension === extension) ?? {
      brotliBytes: 0,
      extension,
      files: 0,
      gzipBytes: 0,
      rawBytes: 0,
    }
  );
}

function listFiles(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      return listFiles(entryPath);
    }

    return statSync(entryPath).isFile() ? [entryPath] : [];
  });
}

function payloadDeltaTable(
  rows: Array<[string, PayloadGroup, PayloadGroup]>,
): string {
  const tableRows = rows.map(([label, baseline, experiment]) => [
    label,
    formatBytes(baseline.rawBytes),
    formatDelta(experiment.rawBytes - baseline.rawBytes),
    formatBytes(baseline.gzipBytes),
    formatDelta(maybeDelta(experiment.gzipBytes, baseline.gzipBytes)),
    formatBytes(baseline.brotliBytes),
    formatDelta(maybeDelta(experiment.brotliBytes, baseline.brotliBytes)),
  ]);

  return [
    "| Group | Baseline raw | Raw delta | Baseline gzip | Gzip delta | Baseline Brotli | Brotli delta |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...tableRows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function recommendationText(
  baseline: PayloadReport,
  experiment: PayloadReport,
): string {
  const htmlBrotliDelta = maybeDelta(
    experiment.htmlFiles.brotliBytes,
    baseline.htmlFiles.brotliBytes,
  );
  const eligibleBrotliDelta = maybeDelta(
    experiment.gzipEligibleFiles.brotliBytes,
    baseline.gzipEligibleFiles.brotliBytes,
  );

  if (
    htmlBrotliDelta !== undefined &&
    eligibleBrotliDelta !== undefined &&
    htmlBrotliDelta <= 0 &&
    eligibleBrotliDelta <= 0
  ) {
    return [
      "Payload moved in the right direction. This is still not enough for",
      "production adoption: run visual, dark-mode, accessibility, HTML, and",
      "Lighthouse checks against the copied output before wiring Beasties into",
      "the build.",
    ].join(" ");
  }

  return [
    "Do not adopt from payload data alone. The first-pass Beasties output does",
    "not clearly reduce compressed HTML/eligible payload, so any production",
    "move would need a measured FCP/LCP win large enough to justify the extra",
    "inline CSS and stylesheet-loading complexity.",
  ].join(" ");
}

function maybeDelta(
  experiment: number | undefined,
  baseline: number | undefined,
): number | undefined {
  if (experiment === undefined || baseline === undefined) {
    return undefined;
  }

  return experiment - baseline;
}

function formatBytes(bytes: number | undefined): string {
  if (bytes === undefined) {
    return "n/a";
  }

  return `${new Intl.NumberFormat("en-US").format(bytes)} B`;
}

function formatDelta(delta: number | undefined): string {
  if (delta === undefined) {
    return "n/a";
  }

  const prefix = delta > 0 ? "+" : "";

  return `${prefix}${formatBytes(delta)}`;
}

function readValueArg(
  args: readonly string[],
  name: string,
): string | undefined {
  const index = args.indexOf(name);

  return index === -1 ? undefined : args[index + 1];
}

async function runCli(args = process.argv.slice(2)): Promise<number> {
  if (args.includes("--help") || args.includes("-h")) {
    console.log(
      `Usage: bun run payload:critical-css:experiment [--source dist] [--out tmp/critical-css-experiment/dist-beasties] [--report tmp/critical-css-experiment/report.md]`,
    );

    return 0;
  }

  const sourceDir = readValueArg(args, "--source") ?? "dist";
  const outputDir =
    readValueArg(args, "--out") ??
    path.join(defaultOutputRoot, "dist-beasties");
  const reportFile =
    readValueArg(args, "--report") ?? path.join(defaultOutputRoot, "report.md");

  try {
    const report = await runCriticalCssExperiment({
      outputDir,
      reportFile,
      sourceDir,
    });
    console.log(report);

    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));

    return 1;
  }
}

if (import.meta.main) {
  process.exitCode = await runCli();
}
