const defaultOutputPath = path.join(
  process.cwd(),
  "docs/generated/platform-reference.md",
);

interface GeneratePlatformReferencesCliIo {
  stderr: Pick<typeof process.stderr, "write">;
  stdout: Pick<typeof process.stdout, "write">;
}

interface JsonSchemaField {
  defaultValue: string;
  path: string;
  required: string;
  type: string;
}

type JsonRecord = Record<string, unknown>;

/**
 * Builds the generated platform reference Markdown from current source
 * contracts.
 *
 * @returns Deterministic generated Markdown.
 */
export function generatedPlatformReferenceMarkdown(): string {
  return [
    "# Generated Platform Reference",
    "",
    "> Generated by `bun run docs:references`. Do not edit by hand.",
    "",
    "This file is generated from platform schemas and registries so docs can",
    "reference current contracts without copying implementation facts by hand.",
    "",
    ...siteConfigReferenceSection(),
    ...frontmatterReferenceSection(),
    ...routeReferenceSection(),
    ...featureReferenceSection(),
    ...visibilityReferenceSection(),
    ...metadataReferenceSection(),
    ...mediaReferenceSection(),
    ...authorDiagnosticReferenceSection(),
    ...sourceArtifactReferenceSection(),
    ...qaCommandReferenceSection(),
    "",
  ].join("\n");
}

/**
 * Formats generated platform reference Markdown with the repository Markdown
 * formatter so generated docs and `fix:markdown` share one canonical shape.
 *
 * @param markdown Raw generated Markdown.
 * @param outputPath Path used for parser inference and diagnostics.
 * @returns Prettier-canonical Markdown.
 */
async function formatGeneratedPlatformReferenceMarkdown(
  markdown: string,
  outputPath = defaultOutputPath,
): Promise<string> {
  const options = await resolvePrettierConfig(defaultOutputPath);

  return formatWithPrettier(markdown, {
    ...options,
    filepath: outputPath,
  });
}

/**
 * Runs the platform reference generator CLI.
 *
 * @param args CLI arguments.
 * @param io Output writers.
 * @returns Process exit code.
 */
export async function runGeneratePlatformReferencesCli(
  args = Bun.argv.slice(2),
  io: GeneratePlatformReferencesCliIo = {
    stderr: process.stderr,
    stdout: process.stdout,
  },
): Promise<number> {
  if (args.includes("--help")) {
    io.stdout.write(usage());

    return 0;
  }

  const outputPath = outputPathFromArgs(args);
  const quiet = args.includes("--quiet");
  const check = args.includes("--check");
  const text = await formatGeneratedPlatformReferenceMarkdown(
    generatedPlatformReferenceMarkdown(),
    outputPath,
  );

  if (check) {
    const existingText = readFileSync(outputPath, "utf8");

    if (existingText === text) {
      if (!quiet) {
        io.stdout.write(
          `Generated platform reference is current at ${projectRelativePath(
            outputPath,
          )}.\n`,
        );
      }

      return 0;
    }

    io.stderr.write(
      `Generated platform reference is stale at ${projectRelativePath(
        outputPath,
      )}. Run bun run docs:references.\n`,
    );

    return 1;
  }

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, text);

  if (!quiet) {
    io.stdout.write(
      `Wrote generated platform reference to ${projectRelativePath(
        outputPath,
      )}.\n`,
    );
  }

  return 0;
}

