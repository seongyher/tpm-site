function schemaFields(schema: unknown): JsonSchemaField[] {
  return collectSchemaFields(recordValue(schema), "").sort((left, right) =>
    left.path.localeCompare(right.path),
  );
}

function collectSchemaFields(
  schema: JsonRecord,
  prefix: string,
): JsonSchemaField[] {
  const properties = recordValue(schema["properties"]);
  const required = new Set(arrayValue(schema["required"]).filter(isString));
  const fields: JsonSchemaField[] = [];

  for (const [key, value] of Object.entries(properties)) {
    const fieldSchema = recordValue(value);
    const fieldPath = prefix === "" ? key : `${prefix}.${key}`;
    fields.push({
      defaultValue: defaultValueLabel(fieldSchema),
      path: fieldPath,
      required: required.has(key) ? "yes" : "no",
      type: schemaTypeLabel(fieldSchema),
    });
    fields.push(...collectSchemaFields(fieldSchema, fieldPath));
  }

  return fields;
}

function schemaTypeLabel(schema: JsonRecord): string {
  const enumValues = arrayValue(schema["enum"]);
  if (enumValues.length > 0) {
    return `enum: ${enumValues.map(String).join(", ")}`;
  }

  const type = schema["type"];
  if (typeof type === "string") {
    return type;
  }

  if (Array.isArray(type)) {
    return type.filter(isString).join(" | ");
  }

  const anyOf = arrayValue(schema["anyOf"]).map(recordValue);
  if (anyOf.length > 0) {
    return anyOf.map(schemaTypeLabel).join(" | ");
  }

  const oneOf = arrayValue(schema["oneOf"]).map(recordValue);
  if (oneOf.length > 0) {
    return oneOf.map(schemaTypeLabel).join(" | ");
  }

  return "$ref" in schema ? "reference" : "unknown";
}

function defaultValueLabel(schema: JsonRecord): string {
  return "default" in schema ? JSON.stringify(schema["default"]) : "";
}

function compareFirstColumn(
  left: readonly string[],
  right: readonly string[],
): number {
  return (left[0] ?? "").localeCompare(right[0] ?? "");
}

function table(headers: readonly string[], rows: readonly string[][]): string {
  const header = `| ${headers.map(escapeTableCell).join(" | ")} |`;
  const separator = `| ${headers.map(() => "---").join(" | ")} |`;
  const body = rows.map((row) => `| ${row.map(escapeTableCell).join(" | ")} |`);

  return [header, separator, ...body].join("\n");
}

function escapeTableCell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function imageSchemaContext(): { image: () => z.ZodType<ImageMetadata> } {
  return {
    image: () =>
      z
        .string()
        .min(1)
        .transform(
          (source): ImageMetadata => ({
            format: "jpg",
            height: 0,
            src: source,
            width: 0,
          }),
        ),
  };
}

function recordValue(value: unknown): JsonRecord {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return {};
  }

  return Object.fromEntries(Object.entries(value));
}

function arrayValue(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function isString(value: unknown): value is string {
  return typeof value === "string";
}

function outputPathFromArgs(args: readonly string[]): string {
  const outputIndex = args.indexOf("--output");

  if (outputIndex === -1) {
    return defaultOutputPath;
  }

  const outputValue = args[outputIndex + 1];

  if (outputValue === undefined || outputValue.startsWith("--")) {
    throw new Error("Missing value for --output.");
  }

  return path.resolve(outputValue);
}

